const MAX_ENTRIES = 500;   // 紀錄上限，避免無限成長塞爆儲存空間
const RECENT_MEMORY = CARDS.length;   // 記住完整牌組的一輪，避免 81 張內過早重複

/* 兩種執行環境：Claude artifact 有 window.storage，一般網頁沒有，
   後者退回 localStorage，兩邊都存不了才回報失敗。 */
const hasArtifactStorage = () => typeof window !== "undefined" && !!window.storage;
const hasLocalStorage = () => {
  try {
    if (typeof window === "undefined" || !window.localStorage) return false;
    window.localStorage.setItem("__t", "1");
    window.localStorage.removeItem("__t");
    return true;
  } catch (e) {
    return false; // 無痕模式或被停用
  }
};

async function storageGet(key) {
  if (hasArtifactStorage()) {
    try {
      const r = await window.storage.get(key, false);
      if (r?.value) return JSON.parse(r.value);
    } catch (e) { /* 還沒有資料，往下試 localStorage */ }
  }
  if (hasLocalStorage()) {
    try {
      const raw = window.localStorage.getItem(`xinzhiyu:${key}`);
      return raw ? JSON.parse(raw) : null;
    } catch (e) { return null; }
  }
  return null;
}

async function storageSet(key, value) {
  const json = JSON.stringify(value);
  if (hasArtifactStorage()) {
    try {
      await window.storage.set(key, json, false);
      return true;
    } catch (e) { /* 往下試 localStorage */ }
  }
  if (hasLocalStorage()) {
    try {
      window.localStorage.setItem(`xinzhiyu:${key}`, json);
      return true;
    } catch (e) { return false; }
  }
  return false;
}

