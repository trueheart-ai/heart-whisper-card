/* Fisher-Yates 洗牌：每一種排列的機率相等。 */
function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/*
   抽卡防重複：
   1. 同一個牌池還有「最近沒出現過」的牌時，優先只從那些牌抽。
   2. 牌池真的抽過一輪後才允許重複；重新進入循環時，盡量避開剛抽到的牌。
   3. 三卡模式仍保證同一次抽出的三張互不相同。
*/
function drawUnique(pool, count, excludeIds = []) {
  if (!Array.isArray(pool) || pool.length === 0 || count <= 0) return [];

  const poolIdSet = new Set(pool.map((c) => c.id));
  const recentInPool = excludeIds.filter((id) => poolIdSet.has(id));
  const recentSet = new Set(recentInPool);
  const fresh = pool.filter((c) => !recentSet.has(c.id));

  if (fresh.length >= count) {
    return shuffle(fresh).slice(0, count);
  }

  // 牌池已經走完一輪。若還有少量未出現牌，先保留它們，再從新一輪補足。
  const picked = shuffle(fresh);
  const pickedIds = new Set(picked.map((c) => c.id));
  const need = count - picked.length;

  // 新一輪至少避開剛剛才出現的牌；牌池太小時才放寬。
  const maxBlock = Math.max(0, pool.length - need);
  const blockCount = Math.min(Math.max(1, need), maxBlock);
  const immediateBlock = new Set(recentInPool.slice(0, blockCount));

  let refill = shuffle(pool.filter((c) => !pickedIds.has(c.id) && !immediateBlock.has(c.id)));
  if (refill.length < need) {
    refill = shuffle(pool.filter((c) => !pickedIds.has(c.id)));
  }

  return [...picked, ...refill.slice(0, need)].slice(0, count);
}

