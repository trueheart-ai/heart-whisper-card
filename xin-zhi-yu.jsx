/* 舊紀錄存的是卡名（e.card），新紀錄存 id（e.cardId），兩種都要讀得出來 */
function entryCard(entry) {
  if (!entry) return null;
  if (entry.cardId != null) return cardById(entry.cardId) || null;
  if (entry.card) return CARDS.find((c) => c.name === entry.card) || null;
  return null;
}
function entryCardName(entry) {
  const c = entryCard(entry);
  return c ? c.name : (entry?.card || "");
}

