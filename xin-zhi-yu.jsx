/* 一年 365 句：依月日固定對應，Jan 1 到 Dec 31 每天不同；2/29 使用專屬句子。 */
const LEAP_DAY_QUOTE = "今天是多出來的一天，也許可以把它留給一件平常總說沒時間做的小事。";
function dayOfYear365Index(date = new Date()) {
  const monthDays = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
  const month = date.getMonth();
  const day = date.getDate();
  let index = day - 1;
  for (let i = 0; i < month; i++) index += monthDays[i];
  return Math.max(0, Math.min(364, index));
}
function todayDailyQuote() {
  const d = new Date();
  if (d.getMonth() === 1 && d.getDate() === 29) return LEAP_DAY_QUOTE;
  return DAILY_QUOTES[dayOfYear365Index(d)];
}
/* 其他短句仍可依日期循環使用。 */
function dailyIndex(len) {
  const d = new Date();
  const localMidnight = new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime();
  return Math.floor(localMidnight / 86400000) % len;
}
