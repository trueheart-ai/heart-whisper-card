/* ============================================================
   抽卡儀式
   ============================================================ */
function RitualStage({ mode, deckKey, onComplete, recentIds = [] }) {
  const [stage, setStage] = useState("idle"); // idle, flipping, revealed
  const [result, setResult] = useState(null);
  const runningRef = useRef(false);

  const runRitual = async () => {
    if (runningRef.current) return; // 防連點重複觸發抽卡動畫
    runningRef.current = true;
    setResult(null);

    // v2.19.14：移除「深呼吸／想著現在最在意的事」等待環節。
    // 點下按鈕後直接進入翻牌，讓抽卡節奏更俐落。
    setStage("flipping");
    await sleep(520);

    let drawn;
    const pool = poolForDeck(deckKey);
    if (mode === "triple") drawn = drawUnique(pool.length >= 3 ? pool : CARDS, 3, recentIds);
    else drawn = drawUnique(pool, 1, recentIds)[0];

    setResult(drawn);
    await sleep(120);
    setStage("revealed");
    runningRef.current = false;
    onComplete && onComplete(drawn);
  };

  const singleCard = mode !== "triple" ? result : null;

  return (
    <div className="ritual-stage" style={{ position: "relative", minHeight: 400 }}>

      {mode === "triple" && stage === "revealed" && Array.isArray(result) ? (
        <div className="triple-card-preview">
          {result.map((c, index) => (
            <div key={c.id} className="triple-card-slot">
              <span className="triple-card-label">{["此刻", "放下", "前行"][index]}</span>
              <CardFace card={c} flipped stage="revealed" compact />
            </div>
          ))}
        </div>
      ) : (
        <CardFace
          card={singleCard}
          flipped={stage === "revealed" || (mode === "triple" && stage === "flipping")}
          stage={stage}
        />
      )}

      {stage === "idle" && (
        <div style={{ textAlign: "center", marginTop: 34 }}>
          <PrimaryButton onClick={runRitual}>
            開始抽卡
          </PrimaryButton>
        </div>
      )}
    </div>
  );
}

